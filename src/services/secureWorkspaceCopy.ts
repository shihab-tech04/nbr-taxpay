export function getSecureWorkspaceCopy(language: string) {
  return language === 'bn' ? SECURE_WORKSPACE_COPY.bn : SECURE_WORKSPACE_COPY.en;
}

export function secureWorkspaceMessage(language: string, key: SecureWorkspaceMessageKey, detail?: string) {
  const message = getSecureWorkspaceCopy(language).messages[key];
  return detail ? message + ' ' + detail : message;
}

export function localizeDraftValidationError(error: string, language: string) {
  return language === 'bn' ? DRAFT_VALIDATION_BN[error] ?? error : error;
}
