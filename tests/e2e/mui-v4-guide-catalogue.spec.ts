import {expect,test} from '@playwright/test';
test('MUI head catalogue controls preserve original native search, group filter, paging and blocked source decisions',async({page})=>{
 await page.goto('/?action=head_catalogue&lang=en');
 const region=page.locator('[data-mui-citizen-region="head-catalogue"]');
 const search=region.getByRole('searchbox',{name:/Search by head ID/});
 const group=region.getByLabel('Original source group');
 await expect(search).toHaveClass(/MuiInputBase-input/);
 await expect(group).toHaveClass(/MuiNativeSelect-select/);
 await expect(region.getByRole('button',{name:'Previous page'})).toBeDisabled();
 await region.getByRole('button',{name:'Next page'}).click();
 await expect(region.getByText('Page 2 of 9')).toBeVisible();
 await search.fill('19AAAAA');
 await expect(region.getByText('Matching source records: 1 / 170')).toBeVisible();
 await expect(region.getByText(/OWNER REVIEW REQUIRED/)).toBeVisible();
 await search.fill('not-a-tax-head-xyz');
 await expect(region.getByText('Matching source records: 0 / 170')).toBeVisible();
 await search.fill('');
 await group.selectOption('Source Tax');
 await expect(region.getByText('Matching source records: 127 / 170')).toBeVisible();
 await expect(region.getByRole('button',{name:'Pay',exact:true})).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2);
});
test('MUI user guide keeps native FAQ semantics, guide search and topic/device selection',async({page})=>{
 await page.goto('/?action=user_guide&lang=en');
 const guide=page.locator('[data-mui-citizen-region="user-guide"]');
 await expect(guide.getByRole('button',{name:'Payment basics'})).toHaveClass(/MuiButtonBase-root/);
 await guide.getByRole('button',{name:'Travel tax',exact:true}).click();
 await expect(guide.getByRole('button',{name:'Travel tax',exact:true})).toHaveAttribute('aria-current','true');
 await guide.getByRole('button',{name:'Mobile',exact:true}).click();
 await expect(guide.getByRole('button',{name:'Mobile',exact:true})).toHaveAttribute('aria-pressed','true');
 const search=guide.getByRole('searchbox',{name:'Search the guide'});
 await expect(search).toHaveClass(/MuiInputBase-input/);
 await search.fill('zzz-no-guide-result-xyz');
 await expect(guide.getByRole('heading',{name:'No results found'})).toBeVisible();
 await guide.locator('.public-guide-no-results').getByRole('button',{name:'Clear search'}).click();
 await expect(search).toBeFocused();
 await expect(search).toHaveValue('');
 const faq=guide.locator('.public-guide-questions details').first();
 await faq.locator('summary').click();
 await expect(faq).toHaveAttribute('open','');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2);
});
