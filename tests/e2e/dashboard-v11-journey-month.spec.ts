import {expect,test} from '@playwright/test';

const preview='/?action=taxpayer_home&demoUser=user1';

test('Overview tax-year chart replaces monthly chart while Activity retains its complete month filters',async({page})=>{
  await page.goto(preview);
  const bento=page.getByTestId('taxpayer-overview-bento');
  await expect(bento.getByRole('heading',{name:'Tax trend by year'})).toBeVisible();
  await expect(bento.getByRole('heading',{name:'Monthly activity'})).toHaveCount(0);
  await expect(bento.locator('.taxpay-bento-hero')).toHaveCount(0);
  await expect(bento.getByTestId('dashboard-correction-requests')).toBeVisible();
  await expect(bento.getByRole('heading',{name:'How your tax is covered'})).toBeVisible();
  await bento.getByRole('button',{name:'View all activity'}).click();
  await expect(page.getByRole('heading',{name:'Payments & activity'})).toBeVisible();
  await page.getByRole('button',{name:'Filter',exact:true}).click();
  await page.getByRole('combobox',{name:'Transaction category'}).selectOption('income');
  await page.getByRole('combobox',{name:'Transaction month'}).selectOption('2026-06');
  await expect(page).toHaveURL(/monthFilter=2026-06/);
  await page.reload();
  await page.getByRole('button',{name:'Filter',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Transaction month'})).toHaveValue('2026-06');
  await expect(page.locator('.taxpay-office-register__count')).toContainText('1 / 14');
  await expect(page.getByText('DEMO-PAY-01').filter({visible:true}).first()).toBeVisible();
  await expect(page.getByText('DEMO-PAY-02')).toHaveCount(0);
  await page.getByRole('combobox',{name:'Transaction month'}).selectOption('all');
  await expect(page).not.toHaveURL(/monthFilter=/);
  await page.reload();
  await page.getByRole('button',{name:'Filter',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Transaction month'})).toHaveValue('all');
  await page.getByRole('combobox',{name:'Transaction month'}).selectOption('2026-09');
  await expect(page).toHaveURL(/monthFilter=2026-09/);
  await page.reload();
  await page.getByRole('button',{name:'Filter',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Transaction month'})).toHaveValue('2026-09');
  await page.getByRole('combobox',{name:'Assessment year'}).selectOption('2024-2025');
  await expect(page).not.toHaveURL(/monthFilter=/);
  await page.reload();
  await page.getByRole('button',{name:'Filter',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Transaction month'})).toHaveValue('all');
  await expect(page.getByText('DEMO-PAY-24-01').filter({visible:true}).first()).toBeVisible();
});

test('Tax Journey tab shows every historical payment grouped by calendar year and preserves event details',async({page})=>{
  await page.goto('/?action=history&demoUser=user1');
  const tabs=page.getByRole('navigation',{name:'Activity sections'});
  await tabs.getByRole('button',{name:'Tax journey'}).click();
  const timeline=page.getByTestId('taxpay-payment-journey');
  await expect(timeline).toBeVisible();
  await expect(tabs.getByRole('button',{name:'Tax journey'})).toHaveAttribute('aria-current','page');
  for(const year of ['2026','2025','2024','2023'])await expect(timeline.getByRole('heading',{name:year})).toBeVisible();
  await expect(timeline.locator('li')).toHaveCount(21);
  await expect(timeline.locator('li').first()).toContainText('Pending bank reconciliation');
  await expect(timeline).toContainText('DEMO-PAY-PEND-01');
  await expect(timeline).toContainText('DEMO-ETDS-23-01');
  await expect(timeline.getByText('Treasury settlement',{exact:true})).toHaveCount(0);
  await expect(timeline.getByText('Ledger allocation',{exact:true})).toHaveCount(0);
  await timeline.getByRole('button',{name:'View details for Pending bank reconciliation'}).click();
  const details=page.getByRole('dialog',{name:'Pending bank reconciliation'});
  await expect(details).toContainText('DEMO-PAY-PEND-01');
  await expect(details).toContainText('No settlement or ledger credit assigned');
  await details.getByRole('button',{name:'Close transaction details'}).click();
  await expect(page.getByRole('combobox',{name:'Assessment year',exact:true})).toHaveCount(0);
});
