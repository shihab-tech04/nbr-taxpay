import {expect,test} from '@playwright/test';
test('MUI report form preserves required minimum and maximum length, review and edit state',async({page})=>{
 await page.goto('/?action=incident&lang=en');
 const region=page.locator('[data-mui-citizen-region="incident-report"]');
 const category=region.getByLabel('Issue type');
 const description=region.getByLabel('Short description');
 await expect(category).toHaveClass(/MuiNativeSelect-select/);
 await expect(description).toHaveClass(/MuiInputBase-input/);
 await expect(description).toHaveAttribute('required','');
 await expect(description).toHaveAttribute('minlength','10');
 await expect(description).toHaveAttribute('maxlength','500');
 await region.getByRole('button',{name:'Review details'}).click();
 await expect(region.getByRole('heading',{name:'Review your details'})).toHaveCount(0);
 await category.selectOption('security');
 await description.fill('Example security concern with synthetic data.');
 await region.getByRole('button',{name:'Review details'}).click();
 await expect(region.getByRole('heading',{name:'Review your details'})).toBeVisible();
 await expect(region.getByText('Security concern',{exact:true})).toBeVisible();
 await expect(region.getByText('Example security concern with synthetic data.',{exact:true})).toBeVisible();
 await region.getByRole('button',{name:'Edit details'}).click();
 await expect(description).toHaveValue('Example security concern with synthetic data.');
 await expect(category).toHaveValue('security');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(2);
});
test('MUI ontology controls retain taxonomy choices and keyboard selection',async({page})=>{
 await page.goto('/?action=ontology&lang=en');
 const region=page.locator('[data-mui-citizen-region="ontology"]');
 await expect(region.getByLabel('Search concepts or rules')).toHaveClass(/MuiInputBase-input/);
 await expect(region.getByRole('combobox',{name:'Concept category'})).toHaveClass(/MuiNativeSelect-select/);
 await expect(region.getByRole('button',{name:/Taxpayer/}).first()).toBeVisible();
 const node=region.getByRole('button',{name:/Taxpayer/}).first();
 await node.focus(); await node.press('Enter');
 await expect(node).toHaveAttribute('aria-pressed','true');
 await region.getByLabel('Search concepts or rules').fill('no-such-tax-concept-xyz');
 await expect(region.getByText('Tax Concepts (0)')).toBeVisible();
 await region.getByLabel('Search concepts or rules').fill('');
 await region.getByRole('combobox',{name:'Concept category'}).selectOption('LEGAL_ENTITY');
 await expect(region.getByRole('button',{name:/Taxpayer/}).first()).toBeVisible();
});
