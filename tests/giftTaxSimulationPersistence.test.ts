import assert from 'node:assert/strict';
import test from 'node:test';
import {giftTaxStoryInput} from '../src/services/giftTaxSimulationPersistence';
import {bindPreviewStoryPayer} from '../src/services/simulatedPaymentStory';
import {makeConfirmedReceipt} from '../src/services/confirmedPaymentCertificate';
import {canViewPaymentCertificate} from '../src/services/paymentCertificateModel';
import type {GiftTaxPaymentInput} from '../src/services/giftTaxPaymentGateway';
const input:GiftTaxPaymentInput={donor:{tin:'111111111111',name:'User 1'},donee:{tin:'222222222222',name:'User 2',tag:'friends_family',relationship:'father',otherLabel:null},giftAmountMinor:250000000,estimatedTaxMinor:27200000,description:'Gift of property',giftDate:'2025-01-15',remarks:'বাংলা remarks\nExact',idempotencyKey:'00000000-0000-4000-8000-000000000101',payer:{name:'Sample Payer',phone:'01712345678',email:'',tin:'',noticeReference:''}};
const sessionId='00000000-0000-4000-8000-000000000102';
const id='00000000-0000-4000-8000-000000000103';
test('Gift Tax SQL payload, owner binding, receipt identity and amount reconcile',()=>{
 const story=giftTaxStoryInput(input,'BKASH',sessionId,'user1');
 const scoped=bindPreviewStoryPayer(story,{profileId:'user1',paymentSessionId:sessionId});
 assert.equal(scoped.service,'GIFT_TAX');
 assert.equal(scoped.details.payerId,'user1');
 assert.equal(scoped.details.payerMode,'SELF');
 assert.equal(scoped.amountMinor,27200000);
 assert.equal(scoped.details.assessmentYear,'2025-26');
 assert.equal(scoped.details.challanRemarks,input.remarks);
 assert.deepEqual(giftTaxStoryInput(input,'BKASH',sessionId,'user1'),story);
 const parent={id,service:scoped.service,amountMinor:scoped.amountMinor,status:'SIMULATED_SUCCESS',createdAt:'2026-11-24T06:00:00Z',details:scoped.details};
 const receipt=makeConfirmedReceipt(parent);
 assert.equal(receipt.paymentTransactionId,id);
 assert.equal(receipt.paymentCategory,'GIFT_TAX');
 assert.equal(receipt.totalAmount,272000);
 assert.equal(receipt.paymentRemarks,input.remarks);
 assert.equal(receipt.giftDetails?.donee.tin,input.donee.tin);
 assert.equal(receipt.allocationItems?.[0].taxpayerTin,input.donor.tin);
 assert.equal(receipt.allocationItems?.[0].taxpayerName,input.donor.name);
 assert.equal(receipt.taxCreditStatus,'NOT_APPLICABLE');
 assert.equal(canViewPaymentCertificate(receipt),false);
 assert.throws(()=>makeConfirmedReceipt({...parent,amountMinor:parent.amountMinor+1}));
 assert.throws(()=>giftTaxStoryInput({...input,estimatedTaxMinor:1},'BKASH',sessionId,'user1'));
});
